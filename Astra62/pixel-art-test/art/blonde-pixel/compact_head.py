def _ribbon(image,phase,bob,palette):
    time=math.tau*float(phase)
    step=_pixel(bob)
    def position(x,y):
        tip=max(0.,min(1.,(29-x)/10))*max(0.,min(1.,(y-8)/6))
        loop=max(0.,min(1.,(9-y)/7))
        return (x+tip*.83*math.sin(time-.83)+loop*.24*math.cos(time-.45),
                y+step+tip*1.08*math.sin(time-1.02)+loop*.24*math.sin(2*time-.56))
    p=_brush(image,palette,position)
    # Behind the ear, the trailing strip has a swallow-cut end.
    p.p('pink',[(30,10),(31,11),(29,13),(27,15),(26,16),(25,15),
         (26,13),(23,14),(20,14),(17,15),(18,13),(16,11),(19,11),
         (22,12),(25,12),(28,10)],'roseink')
    p.l('blush',[(18,11),(20,12),(22,12),(24,12),(26,11)])
    p.l('rose',[(25,15),(27,13),(29,12)])
    p.d('pearl',(27,13))
    # The narrow upper loop and the folded broad left loop share a single knot.
    p.p('pink',[(29,10),(29,8),(30,5),(31,3),(32,2),(33,3),(34,5),
         (34,7),(33,9),(31,11)],'roseink')
    p.p('blush',[(30,8),(31,5),(32,3),(33,4),(33,6),(32,8),(31,9)])
    p.l('pearl',[(31,5),(32,3),(32,4)])
    p.l('rose',[(30,9),(31,8),(33,7)])
    p.p('pink',[(30,10),(27,11),(25,11),(23,10),(21,10),(20,9),
         (19,7),(19,5),(21,4),(24,4),(26,5),(28,7),(30,9)],'roseink')
    p.p('blush',[(20,6),(21,5),(24,5),(26,6),(28,8),(29,9),
         (27,9),(25,8),(23,8),(22,9),(21,8)])
    p.l('pearl',[(21,5),(24,5),(26,6)])
    p.l('rose',[(23,9),(25,8),(27,9),(29,10)])
    p.d('blush',(27,10),(29,9))


