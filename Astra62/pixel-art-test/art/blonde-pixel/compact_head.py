def draw_head(image,phase,bob,palette):
    """Paint the right-facing face and tied hair over the collar and near sleeve."""
    step=_pixel(bob)
    p=_brush(image,palette,lambda x,y:(x,y+step))
    _face(p)
    _ribbon(image,phase,bob,palette)
    _fringe(p)
    _ear(p)
    _flower(p)
