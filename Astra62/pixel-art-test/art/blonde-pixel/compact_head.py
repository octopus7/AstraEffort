"""Native 64-pixel portrait and two trailing locks for the compact ribbon elf."""

import math

from pixel_brush import Brush


def _pixel(v):
    return math.floor(v+.5)


def _brush(image, palette, position):
    return Brush(image, lambda points: [position(x, y) for x, y in points], palette)


def draw_ponytail(image,phase,bob,palette):
    """Paint behind both the head and the collar. The two curls have different lag."""
    time=math.tau*float(phase)
    step=_pixel(bob)

    def pen(lag):
        def position(x,y):
            loose=max(0.,min(1.,(31-x)/25))
            delayed=time-lag-.62*loose
            dx=loose*(.91*math.sin(delayed)-.25*math.cos(2*time-lag))
            dy=loose*(1.57*math.sin(delayed-.28)+.29*math.sin(2*time-.35-lag))
            return x+dx,y+step+dy
        return _brush(image,palette,position)

    # The lower lock turns under itself; its open curl ends in a raised point.
    p=pen(.76)
    p.p('ochre',[(32,13),(34,15),(33,19),(31,22),(28,25),(25,26),(22,27),
         (19,27),(15,25),(13,25),(11,26),(10,28),(10,29),(12,30),(14,29),
         (13,31),(11,32),(9,32),(7,31),(5,29),(5,26),(7,24),(10,22),
         (14,21),(18,21),(22,21),(25,20),(29,17)],'umber')
    p.p('honey',[(32,16),(31,20),(28,23),(25,25),(22,26),(20,26),(16,25),
         (13,24),(10,25),(8,27),(8,29),(9,30),(11,31),(9,31),(7,30),
         (6,28),(6,26),(8,24),(12,22),(17,22),(21,23),(25,22),(29,19)])
    p.p('blonde',[(29,20),(27,23),(24,25),(21,25),(17,24),(14,23),
         (11,24),(9,25),(7,27),(7,29),(6,28),(6,26),(8,24),(11,23),
         (15,22),(18,23),(21,24),(24,23),(27,22)])
    p.l('goldlight',[(7,27),(8,25),(11,23),(13,23)])
    p.l('blonde',[(7,29),(8,30),(10,31),(11,31)])
    p.d('goldlight',(9,30),(12,30))
    # The fuller top lock sweeps across the lower mass and returns to a separate tip.
    p=pen(.39)
    p.p('honey',[(32,12),(34,13),(34,16),(32,19),(30,21),(27,22),(24,23),
         (21,23),(18,22),(15,20),(12,19),(10,19),(8,20),(6,21),(5,23),
         (4,22),(4,20),(6,18),(9,16),(12,15),(15,15),(18,16),(21,17),
         (24,17),(27,16),(30,14)],'umber')
    p.p('ochre',[(32,15),(32,17),(30,20),(27,21),(24,22),(21,22),
         (18,21),(15,19),(12,18),(9,18),(12,17),(16,17),(19,18),
         (22,20),(26,19),(30,17)])
    p.p('blonde',[(31,14),(31,16),(28,19),(25,20),(23,21),(20,20),
         (16,18),(13,17),(10,17),(7,19),(5,21),(6,19),(9,17),(12,16),
         (15,16),(18,17),(21,18),(24,18),(28,16)])
    p.p('goldlight',[(28,16),(27,18),(24,20),(21,20),(18,18),(15,17),
         (12,16),(9,17),(11,16),(14,15),(17,16),(21,18),(23,18),(26,17)])
    p.l('shine',[(9,17),(11,16),(14,16),(16,16)])
    p.l('goldlight',[(5,21),(6,19),(8,18)])
    p.l('honey',[(30,19),(28,21),(25,22),(23,22)])


